// v10.1: generates docs/pinout-zh.md, docs/pinout-en.md and the two SVG pin maps from the same data the in-app
// reference panel uses (js/mcu-help.js, js/mcu-examples.js, js/help/<locale>.js). Run: node tools/gen-pinout-docs.js
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const dicts = {};
global.I18N = { add: (code, d) => { dicts[code] = Object.assign(dicts[code] || {}, d); } };
for (const code of ['zh-CN', 'en']) {
  require(path.join(ROOT, 'js/locales', code + '.js'));
  require(path.join(ROOT, 'js/help', code + '.js'));
  require(path.join(ROOT, 'js/i18n-v11', code + '.js'));
}
// v11: sensor parts — names / pins come from the component definitions (Chinese originals → dictionary keys)
global.window = global; global.document = undefined;
const D = require(path.join(ROOT, 'js/mcu-help.js'));
const EX = require(path.join(ROOT, 'js/mcu-examples.js'));
const SX = require(path.join(ROOT, 'js/sensor-examples.js'));
// pin names of the sensor parts, read from the component sources without running the browser code
const PINS = {};
for (const f of ['js/sensors.js', 'js/lcdi2c.js']) {
  const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
  for (const [t] of D.SENSORS) {
    const m = src.match(new RegExp('\\n  ' + t + ': \\{[\\s\\S]*?termNames: (\\[[^\\]]*\\])')) || (t === 'lcdi2c' && f.endsWith('lcdi2c.js') && src.match(/termNames: (\[[^\]]*\])/));
    if (m && !PINS[t]) PINS[t] = JSON.parse(m[1].replace(/'/g, '"'));
  }
}
// parts built by the shared helpers in js/sensors.js use the helper's pin list
for (const [t, how] of D.SENSORS) if (!PINS[t]) PINS[t] = how === 'ana_do' ? ['VCC', 'GND', 'DO', 'AO'] : (t === 'lm35' || t === 'tmp36') ? ['+Vs', 'Vout', 'GND'] : [];
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/pinout-uno.svg'), D.svg.arduino());
fs.writeFileSync(path.join(ROOT, 'docs/pinout-attiny85.svg'), D.svg.attiny85());

const LABEL = {
  'zh-CN': { title: '单片机引脚说明、常规用法与示例', gen: '本文件由 `tools/gen-pinout-docs.js` 根据程序内「引脚说明」面板的同一份数据生成，内容与面板一致。', other: 'English version', otherFile: 'pinout-en.md', port: '端口 / 数据手册名称', toc: '目录', snippet: '示例代码', open: '在程序中：选中开发板或芯片 → 属性面板或程序编辑器工具栏中的「📌 引脚说明」；示例也在顶部「示例电路」菜单中。' },
  en: { title: 'Microcontroller pinout, common usage and examples', gen: 'Generated by `tools/gen-pinout-docs.js` from the same data as the in-app “Pinout” panel, so both always match.', other: '中文版', otherFile: 'pinout-zh.md', port: 'Port / datasheet names', toc: 'Contents', snippet: 'Snippet', open: 'In the app: select the board or chip → “📌 Pinout” in the properties panel or in the program editor toolbar; the examples are also in the “Examples” menu at the top.' },
};
function gen(code, file) {
  const d = Object.assign({}, dicts.en, dicts[code]);
  const t = (k, p) => { let s = d[k] !== undefined ? d[k] : k; if (p) s = s.replace(/\{(\w+)\}/g, (m, x) => (p[x] !== undefined ? p[x] : m)); return s; };
  const L = LABEL[code];
  const part = (type) => t('c.' + type + '.name');
  const wiring = (line) => line.replace(/\{c:(\w+)\}/g, (m, x) => part(x)).replace(/\{w:(\w+)\}/g, (m, x) => t('help.w.' + x));
  const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const simState = (r) => { if (r.absent) return '— ' + t('help.sim.absent'); const s = r.tags.map((x) => D.TAGS[x][1]); return s.every(Boolean) ? '✓ ' + t('help.sim.yes') : s.some(Boolean) ? '◐ ' + t('help.sim.part') : '✗ ' + t('help.sim.no'); };
  let o = '# ' + L.title + '\n\n> ' + L.gen + '  \n> ' + L.open + '  \n> [' + L.other + '](' + L.otherFile + ')\n\n';
  o += '## ' + L.toc + '\n\n';
  for (const b of D.BOARDS) o += '- [' + part(b) + '](#' + b + ')\n';
  o += '- [' + t('help.nav.usage') + '](#usage)\n- [' + t('help.nav.sensors') + '](#sensors)\n- [' + t('help.nav.examples') + '](#examples)\n\n';
  for (const b of D.BOARDS) {
    o += '<a id="' + b + '"></a>\n\n## ' + part(b) + '\n\n' + t('help.intro.' + b) + '\n\n';
    o += '### ' + t('help.nav.pinout') + '\n\n![' + part(b) + '](pinout-' + (b === 'arduino' ? 'uno' : 'attiny85') + '.svg)\n\n';
    o += D.CATS.map((c) => '`' + t('help.cat.' + c) + '`').join(' · ') + ' — ' + t('help.leg.nosim') + '\n\n';
    o += '### ' + t('help.nav.table') + '\n\n| ' + t('help.th.pin') + ' | ' + L.port + ' | ' + t('help.th.func') + ' | ' + t('help.th.sim') + ' |\n|---|---|---|---|\n';
    let prev = null;
    for (const r of D.PINS[b]) {
      const showNote = r.note && r.note !== prev; prev = r.note || null;
      const tags = r.tags.map((x) => (D.TAGS[x][1] && !r.absent ? '' : '~~') + t('help.tag.' + x) + (D.TAGS[x][1] && !r.absent ? '' : '~~')).join(', ');
      o += '| **' + cell(r.p) + '** | ' + cell(r.port || '') + ' | ' + cell(tags + (showNote ? '<br>' + t('help.note.' + r.note) : '')) + ' | ' + simState(r) + ' |\n';
    }
    o += '\n~~' + t('help.tag.' + (b === 'arduino' ? 'int0' : 'xtal')) + '~~ = ' + t('help.sim.no') + '\n\n### ' + t('help.nav.limits') + '\n\n';
    for (let i = 1; i <= D.LIMITS[b]; i++) o += '- ' + t('help.lim.' + b + '.' + i) + '\n';
    o += '\n';
  }
  o += '## ' + t('help.nav.sim') + '\n\n✓ ' + t('help.sim.ok') + '\n\n';
  for (let i = 1; i <= D.SIM_NO; i++) o += '- ✗ ' + t('help.sim.no.' + i) + '\n';
  o += '\n<a id="usage"></a>\n\n## ' + t('help.nav.usage') + '\n\n' + t('help.usage.intro') + '\n\n';
  for (const u of D.USAGE) {
    o += '### ' + t('help.u.' + u.id + '.t') + '\n\n';
    for (let i = 1; i <= u.n; i++) o += t('help.u.' + u.id + '.' + i) + '\n\n';
    if (u.code) o += '```cpp\n' + u.code.join('\n') + '\n```\n\n';
    if (u.ex && u.ex.length) o += '*' + t('help.ex.examples') + ':* ' + u.ex.map((id) => '[' + t('ex.' + id) + '](#ex-' + id + ')').join(' · ') + '\n\n';
  }
  // v11 sensors
  o += '<a id="sensors"></a>\n\n## ' + t('help.nav.sensors') + '\n\n' + t('help.s.intro') + '\n\n';
  o += '| ' + t('help.s.th.part') + ' | ' + t('help.s.th.pins') + ' | ' + t('help.s.th.read') + ' |\n|---|---|---|\n';
  for (const [ty, how] of D.SENSORS) o += '| **' + cell(part(ty)) + '** | ' + cell((PINS[ty] || []).join(' · ')) + ' | ' + cell(t('help.s.how.' + how)) + ' |\n';
  o += '\n';
  for (let i = 1; i <= D.SENS_TIPS; i++) o += '- ' + t('help.s.tip.' + i) + '\n';
  o += '\n';
  for (const id of Object.keys(SX)) {
    const E = SX[id];
    o += '<a id="ex-' + id + '"></a>\n\n### ' + t('ex.' + id) + '\n\n' + t('exd.' + id) + '\n\n';
    o += '**' + t('help.ex.wiring') + '**\n\n' + E.wiring.map((w) => '- ' + wiring(w)).join('\n') + '\n\n';
    o += '```cpp\n' + E.code.replace(/\s+$/, '') + '\n```\n\n';
  }
  o += '<a id="examples"></a>\n\n## ' + t('help.nav.examples') + '\n\n' + t('help.ex.intro') + '\n\n';
  for (const b of D.BOARDS) {
    o += '### ' + part(b) + '\n\n';
    for (const id of Object.keys(EX).filter((x) => EX[x].board === b)) {
      const E = EX[id];
      o += '<a id="ex-' + id + '"></a>\n\n#### ' + t('ex.' + id) + '\n\n' + t('exd.' + id) + '\n\n';
      o += '**' + t('help.ex.wiring') + '**\n\n' + E.wiring.map((w) => '- ' + wiring(w)).join('\n') + '\n\n';
      o += '**' + t('help.ex.usage') + ':** ' + E.usage.map((u) => t('help.u.' + u + '.t')).join(' · ') + '\n\n';
      o += '```cpp\n' + E.code.replace(/\s+$/, '') + '\n```\n\n';
    }
  }
  fs.writeFileSync(path.join(ROOT, 'docs', file), o.replace(/`([^`\n]+)`/g, (m) => m));
  return o.length;
}
console.log('zh', gen('zh-CN', 'pinout-zh.md'), 'en', gen('en', 'pinout-en.md'));
